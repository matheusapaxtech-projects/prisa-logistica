values ('documentos', 'documentos', false, 20971520,
        array['application/pdf', 'image/jpeg', 'image/png', 'image/heic'])
on conflict (id) do update set
  name = excluded.name,
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Sem política de update: objetos são imutáveis (não há upsert/sobrescrita pela API).
create policy documentos_select on storage.objects
  for select to authenticated
  using (
    bucket_id = 'documentos'
    and (select public.pode_ler())
    and (not public.arquivo_restrito(name) or (select public.eh_admin())));
create policy documentos_insert on storage.objects
  for insert to authenticated
  with check (bucket_id = 'documentos' and (select public.pode_editar()));
create policy documentos_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'documentos' and (select public.eh_admin()));

