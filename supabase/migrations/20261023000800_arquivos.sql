-- Migration 0800: arquivos (metadados), bucket privado "documentos" e pendências de documentos.
--
-- tipo_arquivo = catálogo dos 14 tipos do ATUA (ids originais 1..14).
-- arquivo      = metadados; o binário fica em storage.objects (bucket "documentos").
--                Convenção de caminho: pessoa/<pessoa_id>/<arquivo_id>-<nome>
--                                   ou veiculo/<veiculo_id>/<arquivo_id>-<nome>
-- A aplicação grava o objeto no Storage e depois a linha em arquivo; para ler, chama
-- registrar_visualizacao(arquivo_id) e só então gera o link temporário.

-- ---------------------------------------------------------------------------
-- tipo_arquivo
-- ---------------------------------------------------------------------------
-- aplica_pessoa / aplica_veiculo dizem onde o tipo faz sentido (metadado para a tela; não é
-- imposto por constraint). Pelo menos um dos dois precisa ser verdadeiro.
create table public.tipo_arquivo (
  id smallint generated by default as identity primary key,
  nome text not null unique,
  aplica_pessoa boolean not null default false,
  aplica_veiculo boolean not null default false,
  constraint tipo_arquivo_aplica_algum check (aplica_pessoa or aplica_veiculo)
);

