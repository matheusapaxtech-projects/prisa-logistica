-- tipo_arquivo: leitura pode_ler; escrita só admin
create policy tipo_arquivo_select on public.tipo_arquivo
  for select to authenticated using ((select public.pode_ler()));
create policy tipo_arquivo_insert on public.tipo_arquivo
  for insert to authenticated with check ((select public.eh_admin()));
create policy tipo_arquivo_update on public.tipo_arquivo
  for update to authenticated
  using ((select public.eh_admin())) with check ((select public.eh_admin()));
create policy tipo_arquivo_delete on public.tipo_arquivo
  for delete to authenticated using ((select public.eh_admin()));

-- arquivo: restrito só aparece para admin; escrita pode_editar; exclusão só admin
create policy arquivo_select on public.arquivo
  for select to authenticated
  using ((select public.pode_ler()) and (not restrito or (select public.eh_admin())));
create policy arquivo_insert on public.arquivo
  for insert to authenticated with check ((select public.pode_editar()));
create policy arquivo_update on public.arquivo
  for update to authenticated
  using ((select public.pode_editar())) with check ((select public.pode_editar()));
create policy arquivo_delete on public.arquivo
  for delete to authenticated using ((select public.eh_admin()));

