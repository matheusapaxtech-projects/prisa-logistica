-- ---------------------------------------------------------------------------
-- arquivo
-- ---------------------------------------------------------------------------
-- pessoa_id / veiculo_id: on delete cascade (os metadados morrem com o dono). Só admin apaga
-- pessoa/veículo; os objetos do Storage não são removidos pelo banco (a aplicação os limpa).
create table public.arquivo (
  id uuid primary key default gen_random_uuid(),
  tipo_arquivo_id smallint not null references public.tipo_arquivo (id),
  pessoa_id uuid references public.pessoa (id) on delete cascade,
  veiculo_id uuid references public.veiculo (id) on delete cascade,
  storage_path text not null unique,
  nome_original text,
  mime text,
  tamanho_bytes integer,
  numero text,
  validade date,
  restrito boolean not null default false,
  validado_em timestamptz,
  validado_por uuid,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  updated_at timestamptz not null default now(),
  updated_by uuid,
  -- num_nonnulls nunca devolve null; exatamente um dono.
  constraint arquivo_um_dono check (num_nonnulls(pessoa_id, veiculo_id) = 1),
  -- tamanho nulo passa (comparação com null não recusa a linha).
  constraint arquivo_tamanho_nao_negativo check (tamanho_bytes >= 0)
);

create index arquivo_tipo_arquivo_id_idx on public.arquivo (tipo_arquivo_id);
create index arquivo_pessoa_id_idx on public.arquivo (pessoa_id);
create index arquivo_veiculo_id_idx on public.arquivo (veiculo_id);

create trigger arquivo_set_updated_at
  before update on public.arquivo
  for each row execute function public.fn_set_updated_at();

-- ---------------------------------------------------------------------------
-- Funções
-- ---------------------------------------------------------------------------
-- arquivo_restrito: usada pela política de storage.objects. security definer de propósito:
-- o RLS de arquivo esconde linhas restritas de quem não é admin, e um "not exists" sob o RLS
-- do chamador daria verdadeiro justamente para quem NÃO pode ver o objeto.
create function public.arquivo_restrito(p_path text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.arquivo a
    where a.storage_path = p_path and a.restrito
  )
$$;

revoke execute on function public.arquivo_restrito(text) from public, anon;
grant execute on function public.arquivo_restrito(text) to authenticated;

-- registrar_visualizacao: a aplicação chama antes de gerar o link temporário do arquivo.
-- Arquivo inexistente e arquivo restrito (para não admin) dão o mesmo erro, para não revelar
-- a existência de arquivos restritos.
create function public.registrar_visualizacao(p_arquivo uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_restrito boolean;
begin
  if not (select public.pode_ler()) then
    raise exception 'sem permissão para visualizar arquivos' using errcode = '42501';
  end if;

  select a.restrito into v_restrito from public.arquivo a where a.id = p_arquivo;

  if not found or (v_restrito and not (select public.eh_admin())) then
    raise exception 'arquivo não encontrado' using errcode = 'P0002';
  end if;

  insert into public.auditoria (tabela, registro_id, acao, usuario_id)
  values ('arquivo', p_arquivo::text, 'visualizacao', (select auth.uid()));
end $$;

revoke execute on function public.registrar_visualizacao(uuid) from public, anon;
grant execute on function public.registrar_visualizacao(uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- View de pendências de documentos
-- ---------------------------------------------------------------------------
-- Uma linha por pendência. security_invoker: cada usuário vê o que o RLS dele deixa ver.
-- Limitação conhecida: um CONTRATO ou CNH marcado como restrito fica invisível para não admin
-- e, para eles, a pendência (sem contrato / sem CNH) aparece mesmo com o arquivo cadastrado.
create view public.v_pendencias_documentos
with (security_invoker = true) as
select
  'veiculo_arrendado_sem_contrato'::text as tipo_pendencia,
  null::uuid as pessoa_id,
  v.id as veiculo_id,
  null::uuid as arquivo_id,
  'Veículo arrendado ' || v.placa || ' sem contrato' as descricao
from public.veiculo v
where v.arrendado
  and not exists (
    select 1 from public.arquivo a
    join public.tipo_arquivo t on t.id = a.tipo_arquivo_id
    where a.veiculo_id = v.id and t.nome = 'CONTRATO')
union all
select
  'arquivo_vencido'::text,
  a.pessoa_id,
  a.veiculo_id,
  a.id,
  'Arquivo ' || t.nome || ' vencido em ' || to_char(a.validade, 'DD/MM/YYYY')
from public.arquivo a
join public.tipo_arquivo t on t.id = a.tipo_arquivo_id
where a.validade < current_date
union all
select
  'motorista_sem_cnh'::text,
  m.pessoa_id,
  null::uuid,
  null::uuid,
  'Motorista ' || p.nome || ' sem CNH'
from public.motorista m
join public.pessoa p on p.id = m.pessoa_id
where not exists (
  select 1 from public.arquivo a
  join public.tipo_arquivo t on t.id = a.tipo_arquivo_id
  where a.pessoa_id = m.pessoa_id and t.nome = 'CNH')
union all
select
  'motorista_sem_comprovante'::text,
  m.pessoa_id,
  null::uuid,
  null::uuid,
  'Motorista ' || p.nome || ' sem comprovante de residência'
from public.motorista m
join public.pessoa p on p.id = m.pessoa_id
where not exists (
  select 1 from public.arquivo a
  join public.tipo_arquivo t on t.id = a.tipo_arquivo_id
  where a.pessoa_id = m.pessoa_id and t.nome = 'COMP. RESIDÊNCIA');

revoke insert, update, delete, truncate, references, trigger on public.v_pendencias_documentos from anon, authenticated;
revoke select on public.v_pendencias_documentos from anon;
grant select on public.v_pendencias_documentos to authenticated;

