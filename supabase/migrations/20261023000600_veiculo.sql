create table public.veiculo (
  id uuid primary key default gen_random_uuid(),
  -- text e não char(7): atribuir 'abc-1234' a char(7) estoura 22001 antes do trigger normalizar.
  -- O check abaixo garante 7 caracteres maiúsculos depois da normalização.
  placa text not null unique,
  tipo_veiculo_id smallint not null references public.tipo_veiculo (id),
  marca_id smallint references public.marca_veiculo (id),
  modelo text,
  cor text,
  ano_fabricacao smallint,
  ano_modelo smallint,
  renavam varchar(11) unique,
  chassi varchar(25),
  nr_certificado_doc varchar(20),
  exercicio_doc smallint,
  nr_registro_crlv text,
  dt_emissao_crlv date,
  nr_seguranca_crlv text,
  cidade_emplacamento text,
  uf_emplacamento public.uf,
  -- Posse = quem usa/detém; documento = quem consta no CRLV. Diferentes = arrendado.
  -- on delete restrict: proprietário com veículo não pode ser apagado.
  proprietario_posse_id uuid not null references public.proprietario (pessoa_id) on delete restrict,
  proprietario_documento_id uuid not null references public.proprietario (pessoa_id) on delete restrict,
  arrendado boolean generated always as (proprietario_posse_id <> proprietario_documento_id) stored,
  situacao_operacional public.situacao_operacional not null default 'ativo',
  situacao_cadastro public.situacao_cadastro not null default 'pendente',
  recebedor_valores public.recebedor_valores,
  tag_numero text,
  tag_operadora_id smallint references public.operadora_tag (id),
  seguradora text,
  apolice text,
  seguro_validade date,
  tipo_assoalho public.tipo_assoalho,
  comprimento_m numeric(5, 2),
  largura_m numeric(5, 2),
  altura_m numeric(5, 2),
  cmt_t numeric(6, 2),
  pbt_t numeric(6, 2),
  tara_t numeric(6, 2),
  -- Informada; nula = usar pbt_t - tara_t (ver capacidade_carga).
  capacidade_carga_t numeric(6, 2),
  rastreador_empresa text,
  rastreador_modelo text,
  rastreador_numero text,
  rastreamento_tipo public.tipo_rastreamento,
  rastreador_observacao text,
  pgr_sm_automatica boolean,
  nr_frota text,
  ultimo_motorista_id uuid references public.motorista (pessoa_id) on delete restrict,
  venc_ipva date,
  potencia_motor text,
  hp smallint,
  litros_tanque numeric(6, 1),
  aquisicao date,
  vl_compra numeric(12, 2),
  vl_mercado numeric(12, 2),
  km_inicial integer,
  nr_motor text,
  media_padrao_carregado numeric(5, 2),
  media_padrao_vazio numeric(5, 2),
  unidade_operacional_id smallint references public.unidade_operacional (id),
  centro_custo_id smallint references public.centro_custo (id),
  observacao text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  updated_at timestamptz not null default now(),
  updated_by uuid,
  -- placa é not null, então placa_valida (false para null) não precisa de "is null or".
  constraint veiculo_placa_valida check (public.placa_valida(placa)),
  -- Pesos, dimensões e valores não são negativos (null passa: comparação com null não é falsa).
  constraint veiculo_pesos_nao_negativos
    check (cmt_t >= 0 and pbt_t >= 0 and tara_t >= 0 and capacidade_carga_t >= 0),
  constraint veiculo_dimensoes_nao_negativas
    check (comprimento_m >= 0 and largura_m >= 0 and altura_m >= 0),
  constraint veiculo_frota_nao_negativa
    check (hp >= 0 and litros_tanque >= 0 and vl_compra >= 0 and vl_mercado >= 0 and km_inicial >= 0
           and media_padrao_carregado >= 0 and media_padrao_vazio >= 0)
);

