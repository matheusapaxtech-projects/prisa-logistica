-- Normaliza a placa antes do check: 'abc-1234' -> 'ABC1234'.
create function public.fn_veiculo_normalizar()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.placa := public.normalizar_placa(new.placa);
  return new;
end $$;

create trigger veiculo_normalizar
  before insert or update on public.veiculo
  for each row execute function public.fn_veiculo_normalizar();

create trigger veiculo_set_updated_at
  before update on public.veiculo
  for each row execute function public.fn_set_updated_at();

-- Capacidade efetiva: a informada, ou PBT - tara quando não informada.
-- Só lê campos do próprio argumento, por isso immutable. Aceita a sintaxe veiculo.capacidade_carga.
create function public.capacidade_carga(v public.veiculo)
returns numeric
language sql
immutable
set search_path = ''
as $$
  select coalesce(v.capacidade_carga_t, v.pbt_t - v.tara_t)
$$;

-- ---------------------------------------------------------------------------
-- Funções: trigger só pelo próprio trigger; capacidade_carga para quem está logado (views da Task 8)
-- ---------------------------------------------------------------------------
revoke execute on function public.fn_veiculo_normalizar() from public, anon, authenticated;
revoke execute on function public.capacidade_carga(public.veiculo) from public, anon;
grant execute on function public.capacidade_carga(public.veiculo) to authenticated;

